// Load custom local storage listings into the array at runtime if in browser
if (typeof window !== 'undefined') {
  try {
    const savedListings = JSON.parse(localStorage.getItem('hubli_estate_listings') || '[]');
    // Filter out duplicates in case of hot-reloads
    savedListings.forEach(saved => {
      if (!properties.some(p => p.id === saved.id)) {
        properties.push(saved);
      }
    });
  } catch (err) {
    console.error("Error loading local storage custom listings:", err);
  }
}

export const getPropertiesByAssociation = (associationId, type) => {
  return properties.filter(p => p.associationId === associationId && p.associationType === type);
};

export const getFeaturedProperties = () => {
  // Try to feature custom listings first, then standard ones
  return [...properties].reverse().slice(0, 6);
};

export const getPropertyTypes = () => {
  return ["All", ...new Set(properties.map(p => p.type))];
};

export const searchDatabase = (query, filters = {}) => {
  // Always work with fresh arrays
  let results = [...properties];
  
  if (query) {
    const q = query.toLowerCase();
    results = results.filter(p => 
      p.name.toLowerCase().includes(q) ||
      p.location.toLowerCase().includes(q) ||
      p.type.toLowerCase().includes(q) ||
      p.associatedWith.toLowerCase().includes(q)
    );
  }
  
  if (filters.type && filters.type !== "All") {
    results = results.filter(p => p.type === filters.type);
  }
  
  if (filters.minPrice) {
    results = results.filter(p => p.price >= Number(filters.minPrice));
  }
  
  if (filters.maxPrice) {
    results = results.filter(p => p.price <= Number(filters.maxPrice));
  }
  
  if (filters.associationId) {
    results = results.filter(p => p.associationId === filters.associationId && p.associationType === filters.associationType);
  }

  return results;
};
